import fs from 'node:fs';
import path from 'node:path';
import crypto from 'node:crypto';
import assert from 'node:assert/strict';
import { test } from '@playwright/test';
const data = process.env.LOCAL_DATA_DIR;
const output = path.resolve(process.env.QA_OUTPUT_DIR || 'test-results/browser-qa');
const qa = path.join(output, 'exports');
fs.mkdirSync(qa, { recursive: true });
let stage = 'launch';
const checks = [];
const runtimeErrors = [];
const localFailures = [];
const authTraffic = [];
async function run(browser) {
  const credentials = JSON.parse(fs.readFileSync(data + '/local-credentials.json', 'utf8'));
  const contextA = await browser.newContext({ viewport: { width: 1440, height: 1000 }, acceptDownloads: true });
  const contextB = await browser.newContext({ viewport: { width: 1440, height: 1000 }, acceptDownloads: true });
  const admin = await contextA.newPage();
  const other = await contextB.newPage();
  for (const page of [admin, other]) {
    page.setDefaultTimeout(15000);
    page.on('dialog', dialog => dialog.accept().catch(() => {}));
    page.on('pageerror', error => runtimeErrors.push(error.name));
    page.on('response', response => {
      if (/\/api\/auth\/(login|me)$/.test(response.url())) authTraffic.push({ page: page === admin ? 'admin' : 'member', path: new URL(response.url()).pathname, status: response.status() });
      if ((response.status() === 404 || response.status() >= 500) && /^http:\/\/127\.0\.0\.1:(5000|5173)\//.test(response.url())) localFailures.push({ status: response.status(), url: response.url() });
    });
  }
  async function login(page, email, password) {
    const parentStage = stage;
    stage = parentStage + ' / open form';
    if (page.url() !== 'http://127.0.0.1:5173/') await page.goto('http://127.0.0.1:5173/', { waitUntil: 'domcontentloaded' });
    stage = parentStage + ' / email';
    await page.getByPlaceholder('Enter Email').fill(email);
    stage = parentStage + ' / password';
    await page.getByPlaceholder('Enter Password').fill(password);
    stage = parentStage + ' / submit';
    await page.getByRole('button', { name: 'Login', exact: true }).click();
    stage = parentStage + ' / dashboard navigation';
    await page.waitForURL('**/dashboard');
    await page.getByRole('heading', { name: 'Dashboard Overview' }).waitFor();
  }
  stage = 'administrator UI login';
  await login(admin, credentials.adminEmail, credentials.adminPassword);
  assert.equal(await admin.title(), 'Smart Asset Management System');
  checks.push('Administrator signed in through login form');
  await admin.screenshot({ path: output + '/dashboard-preview.png', fullPage: true });
  const stamp = Date.now().toString(36);
  const member = { name: 'Synthetic Browser QA User ' + stamp, email: 'synthetic-browser-' + stamp + '@example.invalid', password: crypto.randomBytes(24).toString('base64url') };
  fs.writeFileSync(data + '/browser-login-' + stamp + '.json', JSON.stringify(member), { flag: 'wx', mode: 0o600 });
  stage = 'viewer registration through UI';
  await other.goto('http://127.0.0.1:5173/register');
  await other.locator('input[name=full_name]').fill(member.name);
  await other.locator('input[name=email]').fill(member.email);
  await other.locator('input[name=password]').fill(member.password);
  await other.locator('input[name=confirm_password]').fill(member.password);
  await other.getByRole('button', { name: 'Register', exact: true }).click();
  await other.waitForURL('http://127.0.0.1:5173/');
  await login(other, member.email, member.password);
  await other.getByRole('link', { name: 'Labs, assets & QR' }).click();
  await other.getByRole('heading', { name: 'Labs Management' }).waitFor();
  assert.equal(await other.getByRole('button', { name: 'Create Lab', exact: true }).count(), 0);
  const denied = await other.evaluate(async () => {
    const response = await fetch('http://127.0.0.1:5000/api/labs', { method: 'POST', headers: { 'Content-Type': 'application/json', Authorization: 'Bearer ' + localStorage.getItem('token') }, body: JSON.stringify({ lab_name: 'Must not be created' }) });
    return response.status;
  });
  assert.equal(denied, 403);
  await other.goto('http://127.0.0.1:5173/users');
  await other.getByText('Only a Super Admin can manage access.').waitFor();
  checks.push('Viewer UI hides management; server rejects forbidden write; direct user-management page is denied');
  stage = 'promote fixture account using user-access screen';
  await admin.getByRole('link', { name: 'User access', exact: true }).click();
  await admin.getByRole('heading', { name: 'User access', exact: true }).waitFor();
  const memberRow = admin.getByText(member.email, { exact: true }).locator('../..');
  const roleId = await memberRow.getByRole('option', { name: 'Technician', exact: true }).getAttribute('value');
  await memberRow.getByRole('combobox').selectOption(roleId);
  await memberRow.getByRole('button', { name: 'Save access' }).click();
  await admin.getByRole('status').filter({ hasText: 'Access updated' }).waitFor();
  stage = 'session revocation / reload';
  await other.reload({ waitUntil: 'domcontentloaded' }).catch(() => {});
  stage = 'session revocation / wait for login';
  await other.waitForURL('http://127.0.0.1:5173/', { waitUntil: 'domcontentloaded' });
  stage = 'promoted technician / login';
  await login(other, member.email, member.password);
  checks.push('Super Admin role promotion works and invalidates the old browser session');
  stage = 'create lab through UI';
  await admin.getByRole('link', { name: 'Labs, assets & QR' }).click();
  const labName = 'Synthetic Browser QA Lab ' + stamp;
  await admin.getByPlaceholder('Lab Name', { exact: true }).fill(labName);
  await admin.getByPlaceholder('Lab Code', { exact: true }).fill('WEB-' + stamp);
  await admin.getByRole('button', { name: 'Create Lab', exact: true }).click();
  const labCard = admin.getByRole('heading', { name: labName, exact: true }).locator('..');
  await labCard.getByRole('button', { name: 'Open Lab', exact: true }).click();
  await admin.waitForURL('**/labs/*');
  const labId = Number(admin.url().split('/').at(-1));
  stage = 'create asset through UI';
  const assetName = 'Synthetic Browser QA Computer ' + stamp;
  const form = admin.locator('form').first();
  await form.locator('[name=asset_name]').fill(assetName);
  await form.locator('[name=asset_code]').fill('WEB-PC-' + stamp);
  await form.locator('[name=brand]').fill('Synthetic QA Brand');
  await form.locator('[name=model]').fill('QA-01');
  await form.locator('[name=purchase_date]').fill('2025-01-01');
  await form.locator('[name=warranty_expiry]').fill('2027-01-01');
  await form.locator('[name=assigned_to]').fill('Synthetic QA custodian');
  await form.locator('[name=asset_condition]').selectOption('Good');
  await form.locator('[name=asset_status]').selectOption('Available');
  await form.getByRole('button', { name: 'Add Asset', exact: true }).click();
  await admin.getByRole('heading', { name: assetName, exact: true }).click();
  await admin.waitForURL('**/asset/*');
  const assetId = Number(admin.url().split('/').at(-1));
  await admin.getByRole('heading', { name: 'Asset health indicators' }).waitFor();
  checks.push('Lab/asset create forms work with warranty/custodian fields and live reliability widget');
  stage = 'create synthetic ticket using UI';
  const issue = 'Synthetic browser QA: Ethernet is connected but DHCP cannot assign an IP address';
  await admin.getByLabel('Describe the fault').fill(issue);
  await admin.getByRole('checkbox', { name: /Synthetic demo\/test ticket/ }).check();
  const createdResponse = admin.waitForResponse(response => response.request().method() === 'POST' && response.url().endsWith('/api/maintenance/add'));
  await admin.getByRole('button', { name: 'Report issue', exact: true }).click();
  const created = await (await createdResponse).json();
  const ticketId = created.id;
  const heading = '#' + ticketId + ' · ' + issue;
  await admin.getByRole('heading', { name: heading, exact: true }).waitFor();
  let ticketCard = admin.getByRole('heading', { name: heading, exact: true }).locator('..');
  await ticketCard.getByText('Open · Medium · Failure · Synthetic test record', { exact: true }).waitFor();
  await ticketCard.getByRole('button', { name: 'Find verified past repairs', exact: true }).click();
  await ticketCard.getByText('No verified historical repair is indexed. Technician diagnosis is required.', { exact: true }).waitFor();
  checks.push('Synthetic ticket is clearly marked; AI assistance and no-history fallback render');
  stage = 'assign technician using UI';
  const technicianSelect = ticketCard.getByLabel('Technician for ticket ' + ticketId);
  const technicianId = await technicianSelect.getByRole('option', { name: member.name, exact: true }).getAttribute('value');
  await technicianSelect.selectOption(technicianId);
  await ticketCard.getByRole('button', { name: 'Assign', exact: true }).click();
  await ticketCard.getByText('Assigned · Medium · Failure · Synthetic test record', { exact: true }).waitFor();
  stage = 'technician repair using UI';
  await other.goto('http://127.0.0.1:5173/asset/' + assetId);
  const techCard = other.getByRole('heading', { name: heading, exact: true }).locator('..');
  await techCard.getByLabel('Next status for ticket ' + ticketId).selectOption('In Progress');
  await techCard.getByRole('button', { name: 'Update status', exact: true }).click();
  await techCard.getByText('In Progress · Medium · Failure · Synthetic test record', { exact: true }).waitFor();
  await techCard.getByLabel('Resolution for ticket ' + ticketId).fill('Synthetic browser fixture: corrected test DHCP configuration and verified gateway connectivity.');
  await techCard.getByLabel('Next status for ticket ' + ticketId).selectOption('Resolved');
  await techCard.getByRole('button', { name: 'Update status', exact: true }).click();
  await techCard.getByText('Resolved · Medium · Failure · Synthetic test record', { exact: true }).waitFor();
  assert.equal(await techCard.getByRole('option', { name: 'Closed', exact: true }).count(), 0);
  stage = 'manager verification using UI';
  await admin.reload();
  ticketCard = admin.getByRole('heading', { name: heading, exact: true }).locator('..');
  await ticketCard.getByLabel('Next status for ticket ' + ticketId).selectOption('Closed');
  await ticketCard.getByRole('button', { name: 'Update status', exact: true }).click();
  await ticketCard.getByText('Closed · Medium · Failure · Synthetic test record', { exact: true }).waitFor();
  checks.push('Assignment, technician progression/resolution and manager-only closure work through UI');
  stage = 'asset export and screenshot';
  const pdfDownload = admin.waitForEvent('download');
  await admin.getByRole('button', { name: 'Download Asset PDF', exact: true }).click();
  await (await pdfDownload).saveAs(qa + '/asset-report.pdf');
  await admin.screenshot({ path: output + '/asset-workspace-preview.png', fullPage: true });
  await admin.goto('http://127.0.0.1:5173/labs/' + labId);
  await admin.getByRole('heading', { name: assetName, exact: true }).waitFor();
  const excelDownload = admin.waitForEvent('download');
  await admin.getByRole('button', { name: 'Export Excel', exact: true }).click();
  await (await excelDownload).saveAs(qa + '/assets.xlsx');
  const qrDownload = admin.waitForEvent('download');
  await admin.getByRole('button', { name: 'Download QR PDF', exact: true }).click();
  await (await qrDownload).saveAs(qa + '/qr-report.pdf');
  checks.push('Asset PDF, lab QR PDF and Excel export files downloaded through UI');
  stage = 'audit verification through UI';
  await admin.getByRole('link', { name: 'Audit integrity', exact: true }).click();
  await admin.getByText('Verification passed', { exact: true }).waitFor();
  await admin.screenshot({ path: output + '/audit-preview.png', fullPage: false });
  checks.push('Audit page verifies the live chain after the browser workflow');
  assert.deepEqual(runtimeErrors, []);
  assert.deepEqual(localFailures, []);
  const report = { passed: true, checks, fixtureIds: { lab: labId, asset: assetId, ticket: ticketId }, pageErrors: runtimeErrors.length, unexpectedLocalFailures: localFailures.length, exportsDirectory: qa };
  fs.writeFileSync(output + '/browser-qa-report.json', JSON.stringify(report, null, 2));
  console.log(JSON.stringify(report, null, 2));
}
test('approved local inventory, permissions, repair and exports workflow', async ({ browser }) => {
  test.skip(process.env.ALLOW_LOCAL_FIXTURES !== '1' || !data, 'Set ALLOW_LOCAL_FIXTURES=1 and LOCAL_DATA_DIR for the approved isolated database.');
  try { await run(browser); } catch (error) {
    const pages = [];
    for (const context of browser.contexts()) for (const page of context.pages()) { const url = new URL(page.url()); pages.push({ url: url.origin + url.pathname }); }
    console.log(JSON.stringify({ failedStage: stage, pages, authTraffic, errorType: error.name, operation: /^(locator\.\w+|page\.\w+):/.exec(String(error.message))?.[1] || 'assertion' }));
    for (const context of browser.contexts()) for (const page of context.pages()) { try { await page.locator('input[type=password]').evaluateAll(elements => elements.forEach(element => { element.value = ''; })); } catch { /* Keep credentials out of failure snapshots. */ } }
    // The original Playwright error can contain password input values; never attach it as cause.
    // eslint-disable-next-line preserve-caught-error
    throw new Error('Browser verification failed at: ' + stage + '. Sensitive details suppressed.');
  }
});
